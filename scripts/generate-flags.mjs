// flags/catalogue.json + flags/safety-never-flags.json -> src/generated/flags.ts (typed constants)
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const cat = JSON.parse(readFileSync(join(root, "flags/catalogue.json"), "utf8"));
const safety = JSON.parse(readFileSync(join(root, "flags/safety-never-flags.json"), "utf8"));
mkdirSync(join(root, "src/generated"), { recursive: true });

const flags = cat.flags.map(({ note, ...f }) => ({ ...f, ...(note ? { note } : {}) }));
const exact = flags.filter((f) => !f.keyPattern);
const constName = (k) => k.replace(/[^A-Za-z0-9]+/g, "_").toUpperCase();

const out = `// GENERATED by scripts/generate-flags.mjs from flags/catalogue.json (KX-08 §09). Do not edit.
export type FlagProduct = "kiorly-clinic" | "kiorex" | "kiorex-account" | "kiorly-pharmacy" | "kiorly-lab" | "kiorly-nurse" | "all";
export type FlagScopeName = "global" | "market" | "org";
export type FlagClassName = "Module" | "Commercial" | "Integration" | "AI" | "Launch-locked";

export interface FlagCatalogueEntry {
  readonly key: string;
  readonly product: FlagProduct;
  readonly scopes: readonly FlagScopeName[];
  readonly class: FlagClassName;
  readonly whenOff: string;
  readonly dependsOn: readonly string[];
  readonly launchLocked: boolean;
  readonly gate: string | null;
  /** Machine-readable gate ids (e.g. GHV1, GHV2, GPR1, GKN1); gate stays the human text. Rev 2.3. */
  readonly gateIds?: readonly string[];
  /** nurse.* flags evaluate only for NURSE-edition organizations (KX-08 §08). Rev 2.3. */
  readonly edition?: "NURSE";
  readonly keyPattern: boolean;
  readonly note?: string;
}

export const FLAG_CATALOGUE = ${JSON.stringify(flags, null, 2)} as const satisfies readonly FlagCatalogueEntry[];

/** Concrete (non-pattern) flag keys. */
export const FLAG_KEYS = ${JSON.stringify(exact.map((f) => f.key), null, 2)} as const;
export type FlagKey = (typeof FLAG_KEYS)[number];

/** Typed constants, e.g. FLAGS.KIOREX_MARKETPLACE === "kiorex.marketplace". */
export const FLAGS = {
${exact.map((f) => `  ${constName(f.key)}: ${JSON.stringify(f.key)},`).join("\n")}
} as const;

/** Pattern keys: clinic.specialty_templates.<code>, market.<country>.live. */
export const FLAG_KEY_PATTERNS = ${JSON.stringify(flags.filter((f) => f.keyPattern).map((f) => f.key), null, 2)} as const;

export interface SafetyControl {
  readonly id: string;
  readonly label: string;
  readonly products: readonly string[];
  readonly forbiddenKeyTokens: readonly string[];
}
/** ADR-025: controls that are never feature flags. */
export const SAFETY_NEVER_FLAGS = ${JSON.stringify(safety.items, null, 2)} as const satisfies readonly SafetyControl[];
`;
writeFileSync(join(root, "src/generated/flags.ts"), out);
console.log(`generated flags.ts (${exact.length} keys, ${flags.length - exact.length} patterns, ${safety.items.length} safety controls)`);

import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { ENVELOPE, EVENTS, buildExample, buildSchema } from "./event-defs.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(root, "events");
mkdirSync(join(out, "examples"), { recursive: true });
const w = (p, o) => writeFileSync(p, JSON.stringify(o, null, 2) + "\n");

w(join(out, "envelope.schema.json"), ENVELOPE);
const index = [];
for (const ev of EVENTS) {
  const file = ev.file ?? ev.type;
  w(join(out, `${file}.schema.json`), buildSchema(ev));
  w(join(out, "examples", `${file}.example.json`), buildExample(ev));
  if (ev.group === "rev23") {
    mkdirSync(join(root, "fixtures/events-v2.3"), { recursive: true });
    w(join(root, "fixtures/events-v2.3", `${file}.json`), buildExample(ev));
  }
  index.push({ type: ev.type, aliases: ev.aliases ?? [], file, producer: ev.producer, aggregateType: ev.aggregateType, status: ev.status });
}
w(join(out, "index.json"), { envelope: "envelope.schema.json", events: index });
console.log(`generated ${EVENTS.length} event schemas + examples`);

// ---- src/generated/events.ts: embedded schemas, examples and TS types ----
const tsType = (s) => {
  if (s === false) return "never";
  if (s === true || !s || Object.keys(s).length === 0) return "unknown";
  if ("const" in s) return JSON.stringify(s.const);
  if (s.enum) return s.enum.map((v) => JSON.stringify(v)).join(" | ");
  const types = Array.isArray(s.type) ? s.type : [s.type];
  const parts = types.map((t) => {
    switch (t) {
      case "string": return "string";
      case "integer": case "number": return "number";
      case "boolean": return "boolean";
      case "null": return "null";
      case "array": return `Array<${tsType(s.items)}>`;
      case "object": {
        if (!s.properties) return "Record<string, unknown>";
        const req = new Set(s.required ?? []);
        const body = Object.entries(s.properties).map(([k, v]) => `${JSON.stringify(k)}${req.has(k) ? "" : "?"}: ${tsType(v)};`).join(" ");
        return `{ ${body} [k: string]: unknown }`;
      }
      default: return "unknown";
    }
  });
  return parts.join(" | ");
};
const typeName = (ev) => {
  const t = ev.file ?? ev.type;
  if (/^[A-Z0-9_]+$/.test(t) || /[._]/.test(t)) return t.split(/[._]/).map((w) => w.charAt(0).toUpperCase() + w.slice(1).toLowerCase()).join("");
  return t.charAt(0).toUpperCase() + t.slice(1);
};
const lines = ["// GENERATED by scripts/generate-events.mjs from scripts/event-defs.mjs. Do not edit.", ""];
lines.push(`export const ENVELOPE_SCHEMA = ${JSON.stringify(ENVELOPE, null, 2)} as const;`, "");
const schemas = {}; const examples = {}; const aliases = {};
for (const ev of EVENTS) {
  const file = ev.file ?? ev.type;
  schemas[ev.type] = buildSchema(ev); examples[ev.type] = buildExample(ev);
  for (const a of ev.aliases ?? []) aliases[a] = ev.type;
}
lines.push(`export const EVENT_SCHEMAS = ${JSON.stringify(schemas, null, 2)} as const;`, "");
lines.push(`export const EVENT_EXAMPLES = ${JSON.stringify(examples, null, 2)} as const;`, "");
lines.push(`/** Alternate type strings accepted by validateEvent (canonical = what Kiorly emits). */`, `export const EVENT_TYPE_ALIASES = ${JSON.stringify(aliases, null, 2)} as const;`, "");
lines.push(`export const EVENT_META = ${JSON.stringify(Object.fromEntries(EVENTS.map((e) => [e.type, { producer: e.producer, aggregateType: e.aggregateType, status: e.status, schemaFile: `${e.file ?? e.type}.schema.json` }])), null, 2)} as const;`, "");
lines.push(`export type EventType = ${EVENTS.map((e) => JSON.stringify(e.type)).join(" | ")};`, "");
lines.push("export interface EventEnvelope<T extends string = string, D = Record<string, unknown>> {", "  eventId: string;", "  type: T;", "  aggregateType: string;", "  aggregateId: string;", "  target?: string;", "  occurredAt: string;", "  data: D;", "}", "");
for (const ev of EVENTS) {
  const name = typeName(ev);
  lines.push(`export type ${name}Data = ${tsType({ type: "object", ...ev.data })};`);
  lines.push(`export type ${name}Event = EventEnvelope<${JSON.stringify(ev.type)}, ${name}Data>;`);
}
lines.push("", "export interface EventMap {");
for (const ev of EVENTS) {
  const name = typeName(ev);
  lines.push(`  ${JSON.stringify(ev.type)}: ${name}Event;`);
}
lines.push("}", "");
mkdirSync(join(root, "src/generated"), { recursive: true });
writeFileSync(join(root, "src/generated/events.ts"), lines.join("\n"));

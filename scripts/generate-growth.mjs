// src/growth-config/*.schema.json + the AcquisitionBlock component of the marketplace OpenAPI -> src/generated/growth-schemas.ts
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "src/growth-config");
const kinds = readdirSync(dir).filter((f) => f.endsWith(".schema.json")).sort();
const configs = {};
for (const f of kinds) configs[f.replace(".schema.json", "")] = JSON.parse(readFileSync(join(dir, f), "utf8"));
const spec = JSON.parse(readFileSync(join(root, "openapi/kiorly-marketplace.v1.openapi.json"), "utf8"));
const acquisition = { $id: "https://contracts.kiorex.com/growth/AcquisitionBlock.schema.json", ...spec.components.schemas.AcquisitionBlock };
mkdirSync(join(root, "src/generated"), { recursive: true });
const out = `// GENERATED by scripts/generate-growth.mjs from src/growth-config/*.schema.json and openapi/kiorly-marketplace.v1.openapi.json. Do not edit.
export const GROWTH_CONFIG_SCHEMAS = ${JSON.stringify(configs, null, 2)} as const;
export type GrowthConfigKindWithSchema = keyof typeof GROWTH_CONFIG_SCHEMAS;
export const ACQUISITION_BLOCK_SCHEMA = ${JSON.stringify(acquisition, null, 2)} as const;
`;
writeFileSync(join(root, "src/generated/growth-schemas.ts"), out);
console.log(`generated growth-schemas.ts (${kinds.length} config kinds + AcquisitionBlock)`);
